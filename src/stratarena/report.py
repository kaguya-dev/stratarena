"""Run artifacts: ``run.json`` is the source of truth; Markdown and the plot derive from it.

A run directory contains:

- ``config.yaml``: the validated configuration, enough to rerun the search;
- ``run.json``: every population, round, ranking and held-out score;
- ``report.md`` and ``evolution.png``: human-readable views, regenerated by
  ``stratarena report <run_dir>`` from ``run.json`` alone.
"""

import json
import platform
from dataclasses import asdict
from pathlib import Path
from typing import Any

import numpy as np
import yaml

from stratarena import __version__
from stratarena.arena import ArenaResult, Standing
from stratarena.search import RunResult
from stratarena.strategy import CodeStrategy, ParamStrategy, Strategy
from stratarena.validation import ValidationResult

RUN_JSON = "run.json"
STRATEGIES_DIR = "strategies"
EXCHANGES_JSONL = "agents/llm_exchanges.jsonl"
REPORT_MD = "report.md"
EVOLUTION_PNG = "evolution.png"


def run_name(result: RunResult) -> str:
    cfg = result.config
    return f"{cfg.problem}-seed{cfg.seed}-{cfg.fingerprint()}"


def _strategy(s: Strategy) -> dict[str, Any]:
    if isinstance(s, ParamStrategy):
        return {"id": s.id, "kind": "param", "params": s.as_dict(), "parents": list(s.parents)}
    return {
        "id": s.id,
        "kind": "code",
        "entrypoint": s.entrypoint,
        "origin": s.origin,
        "sha256": s.digest,
        "source_file": f"{STRATEGIES_DIR}/{s.id}.py",
        "parents": list(s.parents),
    }


def _standing(s: Standing) -> dict[str, Any]:
    return asdict(s)


def _generation(population: tuple[Strategy, ...], arena: ArenaResult) -> dict[str, Any]:
    return {
        "generation": arena.generation,
        "population": [_strategy(s) for s in population],
        "rounds": [
            {
                "index": r.index,
                "instance_seeds": list(r.instance_seeds),
                "standings": [_standing(s) for s in r.standings],
                "eliminated": list(r.eliminated),
            }
            for r in arena.rounds
        ],
        "finalists": [s.id for s in arena.finalists],
        "standings": [_standing(s) for s in arena.standings],
        "ratings": arena.ratings,
    }


def _validation(v: ValidationResult) -> dict[str, Any]:
    return {
        "instance_seeds": list(v.instance_seeds),
        "champion": v.champion_id,
        "champion_rank": v.champion_rank,
        "generalization_gap": v.generalization_gap,
        "overfit_suspected": v.overfit_suspected,
        "entries": [
            {
                "strategy_id": e.strategy_id,
                "kind": e.kind,
                "train_mean": e.train_mean,
                "holdout": _standing(e.holdout),
                "diff_vs_champion": {"mean": e.diff_mean, "low": e.diff_low, "high": e.diff_high},
                "rating": e.rating,
            }
            for e in v.entries
        ],
    }


def to_dict(result: RunResult) -> dict[str, Any]:
    """Serialize a run. Contains no timestamps, so equal seeds give byte-equal files."""
    return {
        "stratarena_version": __version__,
        "environment": {"python": platform.python_version(), "numpy": np.__version__},
        "mode": result.mode,
        "config": result.config.model_dump(mode="json"),
        "champion": _strategy(result.champion),
        "baselines": [_strategy(b) for b in result.baselines],
        "baseline_tracking": result.baseline_tracking,
        "generations": [
            {**_generation(p, a), "tracking": t}
            for p, a, t in zip(result.populations, result.generations, result.tracking, strict=True)
        ],
        "validation": _validation(result.validation),
        "agents": {
            "llm": result.llm,
            "llm_requests": len(result.exchanges),
            "llm_cache_hits": sum(e.cached for e in result.exchanges),
            "events": [asdict(e) for e in result.agent_events],
        },
    }


def write_run(result: RunResult, run_dir: str | Path) -> Path:
    """Write every artifact of ``result`` into ``run_dir`` and return the directory."""
    path = Path(run_dir)
    path.mkdir(parents=True, exist_ok=True)
    config = result.config.model_dump(mode="json")
    (path / "config.yaml").write_text(yaml.safe_dump(config, sort_keys=False), encoding="utf-8")
    data = json.dumps(to_dict(result), indent=2)
    (path / RUN_JSON).write_text(data + "\n", encoding="utf-8")
    code = {s.id: s for p in result.populations for s in p if isinstance(s, CodeStrategy)}
    if code:
        (path / STRATEGIES_DIR).mkdir(exist_ok=True)
        for sid, strategy in code.items():
            header = f"# {sid} ({strategy.origin}), sha256 {strategy.digest}\n"
            (path / STRATEGIES_DIR / f"{sid}.py").write_text(header + strategy.source, "utf-8")
    if result.exchanges:
        out = path / EXCHANGES_JSONL
        out.parent.mkdir(exist_ok=True)
        lines = sorted(
            (json.dumps(asdict(e) | {"key": e.key}, ensure_ascii=False) for e in result.exchanges),
        )
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    render_report(path)
    return path


def render_report(run_dir: str | Path) -> Path:
    """(Re)generate ``report.md`` and ``evolution.png`` from ``run.json``."""
    path = Path(run_dir)
    data = json.loads((path / RUN_JSON).read_text(encoding="utf-8"))
    plot_evolution(data, path / EVOLUTION_PNG)
    md = path / REPORT_MD
    md.write_text(render_markdown(data), encoding="utf-8")
    return md


def problem_label(cfg: dict[str, Any]) -> str:
    """Problem name plus its options, e.g. ``binpacking (n_items=120, profiles=triplets)``."""
    opts = cfg["problem_options"]
    if not opts:
        return str(cfg["problem"])
    parts = [
        f"{k}={','.join(map(str, v)) if isinstance(v, list) else v}"
        for k, v in sorted(opts.items())
    ]
    return f"{cfg['problem']} ({', '.join(parts)})"


def _ci(s: dict[str, Any]) -> str:
    return f"{s['mean']:.4f} [{s['ci_low']:.4f}, {s['ci_high']:.4f}]"


def _elo(r: float | None) -> str:
    return "—" if r is None else f"{r:.0f}"


def _champion_lines(champ: dict[str, Any]) -> list[str]:
    if champ["kind"] == "param":
        return [
            "| Parameter | Value |",
            "|---|---|",
            *(f"| {k} | {v:.4f} |" for k, v in champ["params"].items()),
        ]
    return [
        f"Code strategy written by `{champ['origin']}` (sha256 `{champ['sha256']}`); "
        f"source in [`{champ['source_file']}`]({champ['source_file']})."
    ]


def _cell(text: str, limit: int = 160) -> str:
    text = " ".join(str(text).split()).replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _agent_lines(agents: dict[str, Any]) -> list[str]:
    if not agents["events"]:
        return []
    llm = agents["llm"] or "none"
    lines = [
        "## Agents",
        "",
        f"LLM: `{llm}`, {agents['llm_requests']} requests ({agents['llm_cache_hits']} served "
        f"from the cache; full transcripts in `{EXCHANGES_JSONL}`). Code candidates must load "
        "in the sandbox and pass a smoke test before they compete.",
        "",
        "| Gen | Agent | Action | Strategy | Detail |",
        "|---|---|---|---|---|",
    ]
    for e in agents["events"]:
        sid = f"`{e['strategy_id']}`" if e["strategy_id"] else "—"
        lines.append(
            f"| {e['generation']} | {e['agent']} | {e['action']} | {sid} | {_cell(e['detail'])} |"
        )
    return [*lines, ""]


def render_markdown(data: dict[str, Any]) -> str:
    cfg = data["config"]
    val = data["validation"]
    champ = data["champion"]
    game = data["mode"] == "game"
    score_note = (
        "Scores are mean points per game (win 1, draw 0.5, loss 0), each pair playing both "
        "sides of every instance; Elo is a Bradley-Terry fit of the same games on the Elo "
        "scale."
        if game
        else "Higher scores are better."
    )
    lines = [
        f"# stratarena run: {cfg['problem']}",
        "",
        f"Problem: `{problem_label(cfg)}`.",
        "",
        f"Seed `{cfg['seed']}`, {cfg['generations']} generations of {cfg['population']} "
        f"strategies, {len(val['instance_seeds'])} held-out instances. "
        f"stratarena {data['stratarena_version']}, Python {data['environment']['python']}, "
        f"NumPy {data['environment']['numpy']}.",
        "",
        "Reproduce with `stratarena run --config config.yaml` (config saved next to this file).",
        "",
        score_note,
        "",
        "## Champion",
        "",
        f"`{champ['id']}`"
        + (f", child of {', '.join(champ['parents'])}" if champ["parents"] else ""),
        "",
        *_champion_lines(champ),
        "",
        "## Training, by generation",
        "",
        "Train: mean over that generation's arena instances (new every round, so not "
        "comparable across generations), with 95% bootstrap interval. Tracking: the same "
        f"generation champion on a fixed set of {cfg['tracking_instances']} instances that never "
        "influences selection, comparable across generations"
        + (", playing against the fixed pool of baselines." if game else "."),
        "",
        "| Gen | Rounds | Champion | Train mean [95% CI] | Tracking mean |"
        + (" Elo |" if game else "")
        + " Finalists |",
        "|---|---|---|---|---|" + ("---|" if game else "") + "---|",
    ]
    for g in data["generations"]:
        best = g["standings"][0]
        sid = best["strategy_id"]
        elo = f" {_elo(g['ratings'].get(sid))} |" if game else ""
        lines.append(
            f"| {g['generation']} | {len(g['rounds'])} | `{sid}` | {_ci(best)} "
            f"| {g['tracking'][sid]:.4f} |{elo} "
            f"{', '.join(f'`{f}`' for f in g['finalists'])} |"
        )
    lines += [
        "",
        "## Held-out validation",
        "",
        "Instances never used during the search. Δ is the paired difference to the champion "
        "(positive means better than the champion), with 95% bootstrap interval.",
        "",
        "| Strategy | Kind | Train mean | Held-out mean [95% CI] | Δ vs champion [95% CI] |"
        + (" Elo |" if game else ""),
        "|---|---|---|---|---|" + ("---|" if game else ""),
    ]
    for e in val["entries"]:
        train = "—" if e["train_mean"] is None else f"{e['train_mean']:.4f}"
        d = e["diff_vs_champion"]
        lines.append(
            f"| `{e['strategy_id']}` | {e['kind']} | {train} | {_ci(e['holdout'])} "
            f"| {d['mean']:+.4f} [{d['low']:+.4f}, {d['high']:+.4f}] |"
            + (f" {_elo(e['rating'])} |" if game else "")
        )
    if game and cfg.get("sparring"):
        verdict = (
            "In a game the training and held-out scores are measured against different "
            "fields, so this gap is not an overfitting measure. The baselines were sparring "
            "partners during training, so on the held-out maps they are known opponents."
        )
    elif game:
        verdict = (
            "In a game the training and held-out scores are measured against different "
            "fields (the other survivors vs. finalists plus baselines), so this gap is not an "
            "overfitting measure; compare Δ and Elo on the held-out set instead."
        )
    elif val["overfit_suspected"]:
        verdict = (
            "**Possible overfitting**: the champion's training mean is above its held-out interval."
        )
    else:
        verdict = (
            "No sign of overfitting: the champion's training mean is within or below its "
            "held-out interval."
        )
    lines += [
        "",
        f"Generalization gap (train - held-out) for the champion: "
        f"{val['generalization_gap']:+.4f}. Champion's held-out rank among finalists: "
        f"{val['champion_rank']}. {verdict}",
        "",
        *_agent_lines(data["agents"]),
        "## Evolution",
        "",
        f"![Score by generation]({EVOLUTION_PNG})",
        "",
    ]
    return "\n".join(lines)


def plot_evolution(data: dict[str, Any], out: Path) -> None:
    """Generation champion and finalists on the fixed tracking set, against the baselines."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    gens = [g["generation"] for g in data["generations"]]
    champ = [g["tracking"][g["standings"][0]["strategy_id"]] for g in data["generations"]]
    lows = [min(g["tracking"].values()) for g in data["generations"]]
    highs = [max(g["tracking"].values()) for g in data["generations"]]

    fig, ax = plt.subplots(figsize=(7, 4), dpi=120)
    ax.fill_between(gens, lows, highs, alpha=0.2, color="C0", label="finalists (range)")
    ax.plot(gens, champ, "o-", color="C0", label="generation champion")

    # Baselines with equal scores share one line and one label.
    by_score: dict[float, list[str]] = {}
    for name, score in data["baseline_tracking"].items():
        by_score.setdefault(round(score, 6), []).append(name)
    for i, (score, names) in enumerate(sorted(by_score.items())):
        ax.axhline(
            score,
            color="0.5",
            linestyle=":",
            linewidth=1,
            label=(
                "baselines" + (" (vs the other baselines)" if data["mode"] == "game" else "")
                if i == 0
                else None
            ),
        )
        ax.annotate(
            " = ".join(names),
            (gens[0], score),
            textcoords="offset points",
            xytext=(2, 3),
            fontsize=7,
            color="0.35",
        )

    n = data["config"]["tracking_instances"]
    ax.set_xlabel("generation")
    what = "points vs baselines" if data["mode"] == "game" else "mean score"
    ax.set_ylabel(f"{what} ({n} tracking instances)")
    ax.set_title(f"{problem_label(data['config'])}, seed {data['config']['seed']}", fontsize=10)
    ax.set_xticks(gens)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8, loc="lower right")
    fig.tight_layout()
    fig.savefig(out, metadata={"Software": None})
    plt.close(fig)
